  assert.deepEqual(names(), ['가이드', '샘플', '아이콘']);
  assert.deepEqual(headers.map(header => header.props['aria-sort']), ['ascending', undefined]);
  act(() => buttons[0].props.onClick());
  assert.deepEqual(names(), ['아이콘', '샘플', '가이드']);
  assert.equal(headers[0].props['aria-sort'], 'descending');
