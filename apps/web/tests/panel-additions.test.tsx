  assert.equal(include.props['aria-controls'], `${available.props.id} ${included.props.id}`);
  assert.equal(back.props['aria-controls'], include.props['aria-controls']);
  assert.notEqual(available.props.id, otherAvailable.props.id);
  assert.deepEqual([include.props['aria-disabled'], back.props['aria-disabled']], [true, true]);
  act(() => { include.props.onClick(); back.props.onClick(); });
  assert.deepEqual([names(available), names(included)], [['표지', '아이콘'], ['로고']]);
  check(available, '아이콘', true);
  check(included, '로고', true);
  act(() => include.props.onClick());
  assert.deepEqual([names(available), names(included)], [['표지'], ['아이콘', '로고']]);
  assert.deepEqual(included.findAllByType('input').map(input => input.props.checked), [false, true]);
  assert.deepEqual([include.props['aria-disabled'], back.props['aria-disabled']], [true, false]);
  act(() => back.props.onClick());
  assert.deepEqual([names(available), names(included)], [['표지', '로고'], ['아이콘']]);
  check(available, '표지', true);
  check(available, '로고', true);
  act(() => { include.props.onClick(); include.props.onClick(); });
  assert.deepEqual([names(available), names(included)], [[], ['표지', '아이콘', '로고']]);
  assert.equal(included.findAllByType('input').every(input => !input.props.checked), true);
  for (const name of names(included)) check(included, name, true);
  act(() => { back.props.onClick(); back.props.onClick(); });
  assert.deepEqual([names(available), names(included)], [['표지', '아이콘', '로고'], []]);
  check(available, '표지', true);
  check(available, '표지', false);
  assert.equal(include.props['aria-disabled'], true);
  assert.equal(include.props.disabled, undefined);
  assert.equal(back.props.disabled, undefined);
  assert.deepEqual([names(otherAvailable), names(otherIncluded)], [['표지', '아이콘'], ['로고']]);
  assert.equal(tree.root.findAllByType('ul')[0], available);
  assert.equal(tree.root.findAllByType('ul')[1], included);
  assert.equal(tree.root.findAllByType('button')[0], include);
