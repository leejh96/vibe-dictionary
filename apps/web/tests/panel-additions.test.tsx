  t.after(() => { act(() => tree.unmount()); });
  const [table, other] = tree.root.findAllByType('table');
  const headers = table.findAllByType('th');
  const buttons = table.findAllByType('button');
  const names = (target = table) => target.findByType('tbody').findAllByType('tr').map(row => row.findAllByType('td')[0].findByType('span').children.filter(child => typeof child === 'string').join(''));
