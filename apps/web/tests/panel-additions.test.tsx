  const [available, included, otherAvailable, otherIncluded] = tree.root.findAllByType('ul');
  const [include, back] = tree.root.findAllByType('button');
  const names = (list: typeof available) => list.findAllByType('label').map(label => label.findByType('span').children.join(''));
  const check = (list: typeof available, name: string, checked: boolean) => act(() => list.findAllByType('label').find(label => label.findByType('span').children.join('') === name)!.findByType('input').props.onChange({ currentTarget: { checked } }));
