test('skip navigation bypasses its own repeated controls with real target focus while preserving the current article and native tab order', t => {
  let tree!: ReturnType<typeof create>;
  const focused: { instance: number; preventScroll: boolean }[] = [];
  let instances = 0;
  act(() => { tree = create(<><SkipNavigationDemo /><SkipNavigationDemo /></>, { createNodeMock: element => {
    if (element.type !== 'h4') return null;
    const instance = instances++;
    return { focus(options: { preventScroll: boolean }) { focused.push({ instance, ...options }); } };
  } }); });
  t.after(() => { act(() => tree.unmount()); });
  const [first, other] = tree.root.findAllByType(SkipNavigationDemo);
  const skip = first.findByType('a');
  const heading = first.findByType('h4');
  const article = first.findByType('article');
  const nav = first.findByType('nav');
  const buttons = nav.findAllByType('button');
  const svg = article.findByType('svg');
  assert.equal(first.findAll(node => ['a', 'button'].includes(String(node.type)))[0], skip);
  assert.equal(skip.props.href, `#${heading.props.id}`);
  assert.equal(heading.props.tabIndex, -1);
  assert.equal(article.props['aria-labelledby'], heading.props.id);
  assert.notEqual(heading.props.id, other.findByType('h4').props.id);
  assert.notEqual(article.props.id, other.findByType('article').props.id);
  assert.ok(buttons.every(button => button.props['aria-controls'] === article.props.id));
  assert.ok(first.findAll(node => typeof node.type === 'string').every(node => !node.props.onKeyDown));
  assert.ok(buttons.every(button => button.props.tabIndex === undefined));
  assert.equal(heading.children.join(''), '색의 균형');
  assert.equal(svg.findAllByType('circle').length, 3);
  act(() => buttons[1].props.onClick());
  assert.equal(heading.children.join(''), '글자의 리듬');
  assert.equal(svg.props['aria-label'], '크기가 다른 세 글자');
  assert.equal(svg.findAllByType('text').length, 3);
  assert.deepEqual(buttons.map(button => button.props['aria-current']), [undefined, 'page', undefined]);
  assert.deepEqual(focused, []);
  let prevented = 0;
  act(() => skip.props.onClick({ preventDefault() { prevented++; } }));
  assert.equal(prevented, 1);
  assert.deepEqual(focused, [{ instance: 0, preventScroll: true }]);
  assert.equal(heading.children.join(''), '글자의 리듬');
  act(() => buttons[2].props.onClick());
  assert.equal(heading.children.join(''), '간격의 규칙');
  assert.equal(svg.findAllByType('rect').length, 4);
  act(() => { skip.props.onClick({ preventDefault() { prevented++; } }); skip.props.onClick({ preventDefault() { prevented++; } }); });
  assert.equal(prevented, 3);
  assert.equal(focused.length, 3);
  assert.ok(focused.every(entry => entry.instance === 0 && entry.preventScroll));
  assert.equal(other.findByType('h4').children.join(''), '색의 균형');
  assert.equal(first.findByType('h4'), heading);
  assert.equal(first.findByType('article'), article);
  assert.equal(first.findByType('nav'), nav);
  assert.equal(first.findByType('a'), skip);
  assert.deepEqual(nav.findAllByType('button'), buttons);
});

