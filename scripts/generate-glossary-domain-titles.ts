import { writeFileSync } from 'node:fs';
import { DOMAIN_KNOWLEDGE } from '../packages/catalog/src/domain-knowledge';
import { GLOSSARY_LINK_META } from '../packages/catalog/src/glossary-links';

const linkedIds = new Set(GLOSSARY_LINK_META.flatMap(term => term.relatedDomainIds));
const entries = DOMAIN_KNOWLEDGE.filter(item => linkedIds.has(item.id));
for (const { id } of entries) linkedIds.delete(id);
if (linkedIds.size > 0) {
  throw new Error(`Unknown related domain knowledge IDs: ${[...linkedIds].join(', ')}`);
}

const rows = entries.map(({ id, text }) =>
  `  ${JSON.stringify([id, { ko: text.ko.title, en: text.en.title }])},`,
);
const source = [
  '// Generated by scripts/generate-glossary-domain-titles.ts.',
  "import type { Locale } from './localization';",
  '',
  'export const GLOSSARY_DOMAIN_TITLES: ReadonlyMap<string, Record<Locale, string>> = new Map([',
  ...rows,
  ']);',
  '',
].join('\n');

writeFileSync(new URL('../packages/catalog/src/glossary-domain-titles.ts', import.meta.url), source);
